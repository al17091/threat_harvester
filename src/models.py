import hashlib
from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class SourceType(str, Enum):
    VENDOR_RSS = "vendor_rss"
    WEB_SEARCH = "web_search"
    DARKWEB_ONION = "darkweb_onion"
    TELEGRAM = "telegram"
    X_MONITOR = "x_monitor"


class Severity(str, Enum):
    CRITICAL = "Critical"
    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"
    UNKNOWN = "Unknown"


class JapanRelevance(str, Enum):
    DIRECT = "Direct"  # Directly targeting Japanese organizations/citizens/infrastructure
    INDIRECT = "Indirect"  # Global incident affecting widespread vendors/systems used in Japan
    NONE = "None"  # No noticeable relevance to Japan
    UNKNOWN = "Unknown"


class ThreatItem(BaseModel):
    """Normalized raw threat data gathered from various sources."""

    id: str = Field(description="Unique hash representing this item")
    source_type: SourceType
    source_name: str
    title: str
    url: str | None = None
    summary: str
    raw_content: str | None = None
    published_at: datetime | None = None
    harvested_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    metadata: dict[str, Any] = Field(default_factory=dict)

    @classmethod
    def create(
        cls,
        source_type: SourceType,
        source_name: str,
        title: str,
        url: str | None,
        summary: str,
        raw_content: str | None = None,
        published_at: datetime | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> "ThreatItem":
        identifier = f"{source_type.value}:{source_name}:{url or ''}:{title}"
        item_id = hashlib.sha256(identifier.encode("utf-8")).hexdigest()
        return cls(
            id=item_id,
            source_type=source_type,
            source_name=source_name,
            title=title.strip(),
            url=url.strip() if url else None,
            summary=summary.strip(),
            raw_content=raw_content.strip() if raw_content else None,
            published_at=published_at,
            metadata=metadata or {},
        )


class EnrichedThreat(BaseModel):
    """Enriched threat intelligence generated by Gemini AI."""

    item_id: str
    item: ThreatItem
    severity: Severity = Severity.UNKNOWN
    japan_relevance: JapanRelevance = JapanRelevance.UNKNOWN
    title_ja: str
    summary_ja: str
    impact_analysis_ja: str
    victim_orgs: list[str] = Field(default_factory=list)
    threat_actors: list[str] = Field(default_factory=list)
    attack_type: str | None = None
    recommended_actions_ja: list[str] = Field(default_factory=list)
    analyzed_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
